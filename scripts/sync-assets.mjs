#!/usr/bin/env node
/**
 * @file scripts/sync-assets.mjs
 * @description Sync GLB assets from the external asset directory (MAARIFY_ASSETS_DIR,
 *   default C:\MaarifyAssets) into public/models/<module>/, verifying SHA-256
 *   against manifest.json. Generates src/core/assets/registry.generated.ts.
 *
 * @usage node scripts/sync-assets.mjs
 */

import { createReadStream, existsSync, mkdirSync, readFileSync, writeFileSync } from 'fs';
import { createHash } from 'crypto';
import { join, dirname } from 'path';
import { fileURLToPath } from 'url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = join(__dirname, '..');
const ASSETS_DIR = process.env.MAARIFY_ASSETS_DIR || 'C:\\MaarifyAssets';
const MANIFEST_PATH = join(ASSETS_DIR, 'manifest.json');
const PUBLIC_MODELS_DIR = join(ROOT, 'public', 'models');
const REGISTRY_PATH = join(ROOT, 'src', 'core', 'assets', 'registry.generated.ts');

function sha256File(filePath) {
  return new Promise((resolve, reject) => {
    const hash = createHash('sha256');
    const stream = createReadStream(filePath);
    stream.on('data', (chunk) => hash.update(chunk));
    stream.on('end', () => resolve(hash.digest('hex')));
    stream.on('error', reject);
  });
}

function copyFile(src, dest) {
  mkdirSync(dirname(dest), { recursive: true });
  const data = readFileSync(src);
  writeFileSync(dest, data);
}

function tsStringArray(arr) {
  return `[\n${arr.map((s) => `    '${s}'`).join(',\n')}\n  ]`;
}

async function main() {
  let failed = false;
  let warned = 0;

  console.log(`Asset source dir: ${ASSETS_DIR}`);
  console.log(`Public models dir: ${PUBLIC_MODELS_DIR}`);

  if (!existsSync(MANIFEST_PATH)) {
    console.error(`Manifest not found: ${MANIFEST_PATH}`);
    process.exit(1);
  }

  const manifest = JSON.parse(readFileSync(MANIFEST_PATH, 'utf8'));
  const assets = manifest.assets ?? [];
  console.log(`Found ${assets.length} assets in manifest.`);

  const registryEntries = [];

  for (const asset of assets) {
    const { module, assetName, relativePath, sha256: expectedHash, partIds, totalTriangles } = asset;

    const sourcePath = join(ASSETS_DIR, relativePath);
    const destPath = join(PUBLIC_MODELS_DIR, module, `${assetName}.glb`);
    const destUrl = `/models/${module}/${assetName}.glb`;

    if (!existsSync(sourcePath)) {
      console.warn(`  WARNING: missing source asset ${relativePath} (skipping)`);
      warned += 1;
      continue;
    }

    try {
      const actualHash = await sha256File(sourcePath);
      if (actualHash !== expectedHash) {
        console.error(`  FAIL: SHA-256 mismatch for ${relativePath}`);
        console.error(`    expected: ${expectedHash}`);
        console.error(`    actual:   ${actualHash}`);
        failed = true;
        continue;
      }

      await copyFile(sourcePath, destPath);
      console.log(`  OK: ${relativePath} -> ${destUrl} (${totalTriangles} tris, ${partIds.length} parts)`);

      registryEntries.push({
        module,
        assetName,
        url: destUrl,
        partIds,
        totalTriangles,
      });
    } catch (err) {
      console.error(`  ERROR processing ${relativePath}: ${err.message}`);
      failed = true;
    }
  }

  // Generate the registry
  const lines = [
    '/**',
    ' * Generated asset registry.',
    ' *',
    ' * This file is generated by `scripts/sync-assets.mjs` (npm run sync:assets).',
    ' * It maps typed asset ids to URLs, part ids, and triangle counts.',
    ' * DO NOT EDIT BY HAND — re-run sync:assets when the asset manifest changes.',
    ' *',
    ' * @generated',
    ' */',
    '',
    'export interface AssetRegistryEntry {',
    '  module: string;',
    '  assetName: string;',
    '  url: string;',
    '  partIds: string[];',
    '  totalTriangles: number;',
    '}',
    '',
    'export const ASSET_REGISTRY: AssetRegistryEntry[] = [',
  ];

  for (const entry of registryEntries) {
    lines.push('  {');
    lines.push(`    module: '${entry.module}',`);
    lines.push(`    assetName: '${entry.assetName}',`);
    lines.push(`    url: '${entry.url}',`);
    lines.push(`    partIds: ${tsStringArray(entry.partIds)},`);
    lines.push(`    totalTriangles: ${entry.totalTriangles},`);
    lines.push('  },');
  }

  lines.push('];');
  lines.push('');
  lines.push("export function getAssetUrl(assetName: string): string | undefined {");
  lines.push("  const entry = ASSET_REGISTRY.find((e) => e.assetName === assetName);");
  lines.push("  return entry?.url;");
  lines.push('}');
  lines.push('');
  lines.push("export function getAssetByModule(moduleId: string): AssetRegistryEntry[] {");
  lines.push("  return ASSET_REGISTRY.filter((e) => e.module === moduleId);");
  lines.push('}');
  lines.push('');

  mkdirSync(dirname(REGISTRY_PATH), { recursive: true });
  writeFileSync(REGISTRY_PATH, lines.join('\n'), 'utf8');

  console.log(`\nRegistry written to ${REGISTRY_PATH} (${registryEntries.length} entries)`);
  if (warned > 0) console.log(`\n${warned} warning(s) - missing assets were skipped.`);

  if (failed) {
    console.error('\nSync FAILED: one or more assets had hash mismatches or errors.');
    process.exit(1);
  }

  console.log('\nSync complete.');
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});